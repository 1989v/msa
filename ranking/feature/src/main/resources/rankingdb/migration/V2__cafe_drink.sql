-- Official recipe nutrition; source values remain separate from derived classification/concentration.
CREATE TABLE cafe_drink (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    brand_slug VARCHAR(40) NOT NULL,
    brand_name VARCHAR(255) NOT NULL,
    menu_name VARCHAR(255) NOT NULL,
    menu_name_en VARCHAR(255),
    source_category VARCHAR(255),
    temperature VARCHAR(20) NOT NULL DEFAULT '',
    size_label VARCHAR(60) NOT NULL DEFAULT '',
    volume_ml DECIMAL(14,4),
    serving_basis VARCHAR(255),
    kcal DECIMAL(14,4),
    sugar_g DECIMAL(14,4),
    sodium_mg DECIMAL(14,4),
    carbs_g DECIMAL(14,4),
    fat_g DECIMAL(14,4),
    sat_fat_g DECIMAL(14,4),
    protein_g DECIMAL(14,4),
    caffeine_mg DECIMAL(14,4),
    caffeine_status VARCHAR(30) NOT NULL,
    raw_nutrition TEXT NOT NULL,
    price_krw INT,
    price_note VARCHAR(255),
    allergens TEXT,
    source_url VARCHAR(2048) NOT NULL,
    checked_at DATE NOT NULL,
    notes TEXT,
    drink_group VARCHAR(255) NOT NULL,
    sugar_per_100ml DECIMAL(14,4),
    caffeine_per_100ml DECIMAL(14,4),
    -- 디카페인은 같은 메뉴의 다른 판이므로 caffeine_status를 유일키에 포함한다.
    CONSTRAINT uq_cafe_drink UNIQUE (brand_slug, menu_name, temperature, size_label, caffeine_status),
    INDEX idx_cafe_group (drink_group),
    INDEX idx_cafe_sugar (sugar_g),
    INDEX idx_cafe_caffeine (caffeine_status, caffeine_mg)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
