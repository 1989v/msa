package com.kgd.game.application.party.port

/**
 * 파티 관측 (ADR-0092 SR-9).
 *
 * **릴레이는 형식만 센다.** 방 수·좌석 점유·유휴 종료는 페이로드의 뜻을 몰라도 셀 수 있다.
 * 반면 투표 득표 · 결과 해시 불일치 · 채점 거부 사유는 값의 **의미**를 알아야 세므로
 * 릴레이가 세면 무권위 원칙이 깨진다 — 그래서 여기 선언하고 채점 서버 쪽이 부른다.
 *
 * 관측기 자체는 호스트가 소유한다(횡단 관심사). 그래서 이 모듈에 계측 라이브러리를
 * 새로 붙이지 않고 포트만 둔다 — 구현은 호스트 앱에 있다.
 *
 * **별칭은 어떤 값에도 안 들어간다.** 실명이 들어올 수 있는 자유 텍스트라, 태그로 붙이는
 * 순간 그 관측이 원장이 된다.
 */
interface PartyMetricsPort {

    /** 채점 제출이 거부됐다 — 사유별로 센다 */
    fun scoringRejected(reason: String)

    /** 결과 해시가 다수와 갈렸다 — 「결과가 갈리면 안 된다」의 계측기다 */
    fun hashDiverged(count: Int)

    /** 다수가 없어 판이 무효가 됐다 */
    fun roundVoided()

    /** 판이 확정됐다 — 무효율의 분모 */
    fun roundSettled()
}
