package com.kgd.game.application.party.port

/**
 * 좌석 토큰 (ADR-0092) — 「이 제출이 그 방 그 좌석에서 온 것인가」만 증명한다.
 *
 * **발급은 릴레이가 좌석을 배정하는 그 순간, 그 소켓으로만 한다.** HTTP 엔드포인트가
 * (방 코드 + 좌석 번호)를 받아 내주면 **자칭 사실에 도장을 찍는 것**이고, 공격자가 전 좌석의
 * 토큰을 받아 전원 대신 제출할 수 있다.
 *
 * 아케이드의 세션 토큰과 **서명 대상이 다르다** — 그쪽은 (세션·시드·시작시각)이라 방·판·좌석·세대를
 * 담지 못한다. 그래서 재사용하지 않고 포트를 따로 세운다.
 *
 * ## 막는 것과 못 막는 것
 *
 * | | 막나 | 조건 |
 * |---|---|---|
 * | 관전자의 제출 | O | 좌석이 없으면 토큰이 없다 |
 * | 같은 방 다른 좌석 사칭 | O | 좌석 번호가 서명 안에 있고 발급자가 릴레이일 때만 |
 * | 방 밖에서의 제출 | O | 방 코드가 서명 안에 있다 |
 * | 다음 판 재사용 | O | 판 번호가 서명 안에 있다 |
 * | 같은 코드로 다시 열린 방 | O | 방 생성 시각이 서명 안에 있다 |
 * | 좌석 재점유 후 사용 | O | 좌석 점유 세대가 서명 안에 있다 |
 * | 토큰을 넘겨받은 대리 제출 | X | 소지자 토큰의 성질. 판 단위 만료로 창을 줄이는 것이 상한 |
 * | 원자료 위조 | X | 토큰은 「누가」만 증명하고 「무엇을」은 증명하지 않는다 |
 */
interface PartySeatTokenPort {

    fun issue(claim: SeatClaim): String

    /** 서명이 이 좌석의 것인지. 위조·다른 판·다른 세대는 전부 false */
    fun verify(token: String, claim: SeatClaim): Boolean
}

/**
 * 서명 대상. 여섯 항 중 하나라도 빠지면 위 표의 「막나 O」 한 줄이 X 로 바뀐다.
 */
data class SeatClaim(
    val roomCode: String,
    /** 같은 코드로 다시 열린 방에서 옛 토큰이 살아나지 않게 한다 */
    val roomCreatedMs: Long,
    val roundNo: Int,
    val seat: Int,
    /** 그 좌석이 몇 번째로 점유됐나 — 먼저 나간 사람의 토큰이 새 점유자 자리에서 유효하면 안 된다 */
    val seatEpoch: Int,
)
