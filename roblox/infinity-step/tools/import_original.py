#!/usr/bin/env python3
"""Map exported original coordinates x4; retain source IDs and all geometry metadata."""
from pathlib import Path
import json,math
ROOT=Path(__file__).resolve().parents[1]
def literal(value):
    if isinstance(value,bool):return 'true' if value else 'false'
    if isinstance(value,str):return json.dumps(value,ensure_ascii=False)
    if isinstance(value,(float,int)):return format(value,'.10g')
    if isinstance(value,list):return '{'+','.join(map(literal,value))+'}'
    return '{'+','.join(k+'='+literal(v) for k,v in value.items())+'}'
def generate():
    d=json.loads((ROOT/'data/original-normal-20261028.json').read_text())
    out=['-- GENERATED by tools/import_original.py from unchanged original generator / .NET float adapter.','local Course={version=2,seed=20261028,scale=4,summit=12000}']
    names=['뒷골목','외벽','옥상','마천루','공사장','성층권','블랙홀'];floors=[0,200,600,1100,1700,2300,3000]
    out+=['Course.regions='+literal([dict(name=n,y=h*4) for n,h in zip(names,floors)])]
    platforms=[dict(id='Start',x=0,y=0,z=-8,sx=1040,sz=1040,depth=4,region=1,kind='Solid',grade=0,slopeX=0,slopeZ=0,mover=0,onPath=False,sourceId=-1)]
    for s in d['slabs']:
        if s['dead']:continue
        platforms.append(dict(id=f"Source{s['id']:04d}",sourceId=s['id'],x=s['at']['x']*4,y=s['at']['y']*4,z=s['at']['z']*4,sx=s['halfX']*8,sz=s['halfZ']*8,depth=s['depth']*4,region=s['biome']+1,kind=s['kind'],grade=s['grade'],slopeX=s['slope']['x'],slopeZ=s['slope']['z'],mover=s['mover']+1,onPath=s['onPath'],tilesX=max(1,math.ceil(s['grade']*abs(s['slope']['x'])*s['halfX']*2/.125)),tilesZ=max(1,math.ceil(s['grade']*abs(s['slope']['z'])*s['halfZ']*2/.125))))
    out+=['Course.platforms={']+[literal(p)+',' for p in platforms]+['}']
    out+=['Course.path='+literal([f'Source{i:04d}' for i in d['path']])]
    out+=['Course.links={']+[literal(dict(source=f"Source{l['from']:04d}",target=f"Source{l['to']:04d}",valid=l['valid'],launch=[l['launch'][k]*4 for k in ['x','y','z']],dir=[l['dir'][k] for k in ['x','y','z']],vx=l['vx']*4,vy=l['vy']*4,g=l['g']*4,air=l['air']))+',' for l in d['links']]+['}']
    out+=['Course.movers='+literal([dict(a=[m['a'][k]*4 for k in ['x','y','z']],b=[m['b'][k]*4 for k in ['x','y','z']],period=m['period'],phase=m['phase']) for m in d['movers']])]
    env=[]
    for e in d['environment']:
        l=e['look'];env.append(dict(y=e['y']*4,sky=[l['Sky'][k] for k in ['r','g','b']],fogStart=l['FogStart']*4,fogEnd=l['FogEnd']*4,sunPitch=l['SunPitch'],sunPower=l['SunPower'],gravity=l['Gravity'],wind=[e['wind'][k]*4 for k in ['x','y','z']]))
    out+=['Course.environment='+literal(env)]
    out+=['Course.palette='+literal(dict(body=[[c[k] for k in ['r','g','b']] for c in d['body']],trim=[[c[k] for k in ['r','g','b']] for c in d['trim']],asphalt=[d['asphalt'][k] for k in ['r','g','b']]))]
    old=['Start','Crate','Awning','Exterior','Vent','Balcony','Roof','Tank','Finish']
    out+=['Course.legacy='+literal({name:dict(id=name,x=i*12,y=i*6,z=0,sx=12,sz=12,region=min(3,i//3+1),depth=4) for i,name in enumerate(old)})]
    out+=['''local byId={}
for _,p in Course.platforms do byId[p.id]=p end
function Course.platform(id) return byId[id] end
function Course.resolve(target)
    if target.courseVersion==2 then return byId[target.platformId] end
    if target.courseVersion==1 then return Course.legacy[target.platformId] end
    return nil
end
function Course.resume(alt)
    local found=byId.Start
    for _,id in Course.path do local p=byId[id];if p.y>alt then break end;found=p end
    return found
end
function Course.look(y)
    local samples=Course.environment
    local index=math.clamp(math.floor(y/20)+1,1,#samples)
    local a,b=samples[index],samples[math.min(index+1,#samples)]
    local t=math.clamp((y-a.y)/20,0,1)
    local function blend(x,z) return x+(z-x)*t end
    return {sky={blend(a.sky[1],b.sky[1]),blend(a.sky[2],b.sky[2]),blend(a.sky[3],b.sky[3])},
        fogStart=blend(a.fogStart,b.fogStart),fogEnd=blend(a.fogEnd,b.fogEnd),sunPower=blend(a.sunPower,b.sunPower),
        gravity=blend(a.gravity,b.gravity),wind={blend(a.wind[1],b.wind[1]),0,blend(a.wind[3],b.wind[3])}}
end
return Course''']
    (ROOT/'data/reference-course.luau').write_text('\n'.join(out)+'\n')
    return platforms,d
if __name__=='__main__':generate()
