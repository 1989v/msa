-- ADR-0078 — 회원 식별에서 이메일을 걷어낸다.
--
-- email 은 처음부터 조회 키가 아니었다. findByEmail 이 없고, FE 도 JWT 도 쓰지 않았으며,
-- 메일을 보내는 기능 자체가 없다. 유일한 사용처가 로그인 시 어드민 부트스트랩 비교였는데
-- 그 역할은 member_roles 행으로 이미 남아 있어 코드와 함께 제거했다.
--
-- 남기면 위험만 지고 효용이 없다 — 이메일은 다른 서비스에서도 같은 값이라 유출 시
-- 서비스 간 결합의 만능키가 된다. sub 해시와 성격이 다르다.
--
-- V1 은 Hibernate 가 만든 기존 스키마다(baseline). 이 파일이 첫 실제 마이그레이션이다.

-- 표시 이름을 우리가 만든 닉네임으로 바꾼다. 소셜 계정의 실명이 그대로 남아 있으면
-- 컬럼만 이름을 바꾼 셈이 되어, 지우려던 정보가 그대로 남는다.
-- 회원 id 를 섞어 서로 다른 값이 되게 한다(닉네임은 유일할 필요가 없다 — id 가 그 역할).
UPDATE members
SET name = CONCAT('회원-', id)
WHERE name IS NOT NULL;

ALTER TABLE members DROP COLUMN email;
