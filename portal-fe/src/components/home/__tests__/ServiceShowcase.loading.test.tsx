import { MemoryRouter } from 'react-router-dom';
import { render, screen, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { expect, it, vi } from 'vitest';
const gate = vi.hoisted(() => ({ ready: false }));
vi.mock('../../../hooks/useNearViewport', () => ({ useNearViewport: () => [() => {}, gate.ready] }));
vi.mock('../../../hooks/useReveal', () => ({ useReveal: () => () => {} }));
vi.mock('../../dispenser/DispenserStage', () => ({ default: () => null }));
vi.mock('../../dispenser/PickLine', () => ({ default: () => null }));
vi.mock('../../dispenser/useDispenser', () => ({ useShownItems: (items: unknown) => items }));
vi.mock('../TileGrid', () => ({ default: () => null }));
vi.mock('../../../api/placeApi', () => ({ searchAttractions: vi.fn(async () => ({ attractions: [], totalElements: 0 })) }));
vi.mock('../../../api/gameApi', () => ({ listGames: vi.fn(async () => ({ content: [] })), displayTitle: vi.fn(), genreLabel: vi.fn() }));
vi.mock('../../../api/blogApi', () => ({ fetchPosts: vi.fn(async () => ({ items: [] })) }));
vi.mock('../../../api/shopApi', () => ({ fetchProducts: vi.fn(async () => ({ products: [] })) }));
import { searchAttractions } from '../../../api/placeApi';
import { listGames } from '../../../api/gameApi';
import { fetchPosts } from '../../../api/blogApi';
import { fetchProducts } from '../../../api/shopApi';
import ServiceShowcase from '../ServiceShowcase';
it('keeps service links usable while all four showcase requests are deferred', async () => {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  const content = () => <QueryClientProvider client={client}><MemoryRouter><ServiceShowcase services={[]} /></MemoryRouter></QueryClientProvider>;
  const view = render(content());
  for (const call of [searchAttractions, listGames, fetchPosts, fetchProducts]) expect(call).not.toHaveBeenCalled();
  expect(screen.getByRole('link', { name: /place.1989v.com/ })).toHaveAttribute('href', 'https://place.1989v.com/');
  gate.ready = true;
  view.rerender(content());
  await waitFor(() => { for (const call of [searchAttractions, listGames, fetchPosts, fetchProducts]) expect(call).toHaveBeenCalledOnce(); });
});
